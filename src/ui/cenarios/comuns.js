// Desenho que vários cenários usam: a pessoa (mestre de obras, engenheira, estivador, técnica,
// operária), cada uma com as suas cores.
import { sprite, passo } from './pixel.js';

const CABECA = {
  aba: `
.....cccccc.....
....cccccccc....
..cccccccccccc..`,
  justo: `
................
.....cccccc.....
....cccccccc....`,
};

const CORPO = `
.....pppppp.....
.....poppop.....
.....pppppp.....
......pppp......
....rrrrrrrr....
...rrrrrrrrrr...
...prrrrrrrrp...
...prrrrrrrrp...
....rrrrrrrr....
.....qq..qq.....
.....qq..qq.....
.....qq..qq.....
....ss....ss....`;

/** Uma pessoa andando: `cabeca` é 'aba' (chapéu de aba larga) ou 'justo' (capacete, lenço, cabelo). */
export function pessoa({ cabeca = 'aba', chapeu, pele = '#c68b59', roupa, calca, sapato = '#3d2a1c' }) {
  const s = sprite({ c: chapeu, p: pele, o: '#1f1f1f', r: roupa, q: calca, s: sapato }, CABECA[cabeca] + CORPO);
  return [s, passo(s, 'andar')];
}
